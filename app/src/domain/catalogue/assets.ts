import type { AssetEntry } from "@/domain/engine/types";
import { PRODUCTS } from "./products";

/**
 * The asset manifest: the only place visuals are declared. Everything else refers to an `AssetId`.
 * All entries are original to this project (generated SVG / drawn by us); there is no third-party imagery.
 */
const OWN = "Original artwork created for this project; no third-party licence.";

const productAssets: AssetEntry[] = PRODUCTS.map((p) => ({
  id: p.assetId,
  kind: "schematic",
  alt: `${p.name} door (schematic)`,
  license: "Generated by the app's schematic renderer from the product's defaults.",
}));

const galleryAssets: AssetEntry[] = [
  { id: "gallery.house-1", kind: "image", src: "/gallery/house-1.svg", alt: "House with gray siding", license: OWN },
  { id: "gallery.house-2", kind: "image", src: "/gallery/house-2.svg", alt: "House with red brick", license: OWN },
  { id: "gallery.house-3", kind: "image", src: "/gallery/house-3.svg", alt: "Craftsman house with stucco", license: OWN },
  { id: "gallery.room-1", kind: "image", src: "/gallery/room-1.svg", alt: "Living room wall", license: OWN },
];

export const ASSETS: Readonly<Record<string, AssetEntry>> = Object.fromEntries(
  [...productAssets, ...galleryAssets].map((a) => [a.id, a]),
);

export function getAsset(id: string): AssetEntry {
  const a = ASSETS[id];
  if (!a) throw new Error(`Unknown asset "${id}". Add it to the asset manifest first.`);
  return a;
}
